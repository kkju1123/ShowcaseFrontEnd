export default function AboutMe({ language = "en" }) {
  const t = content[language] || content.en;
  const [index, setIndex] = useState(0);
  const [copiedValue, setCopiedValue] = useState(null);

  useEffect(() => {
    const timer = setInterval(() => {
      setIndex((prev) => (prev + 1) % bannerImages.length);
    }, 4000); // 每4秒切换一次
    return () => clearInterval(timer);
  }, []);
  // navigator.clipboard 只在 HTTPS / localhost 下可用，其他情况退回 execCommand
  function writeClipboard(text) {
    if (navigator.clipboard && window.isSecureContext) {
      return navigator.clipboard.writeText(text);
    }
    return new Promise((resolve, reject) => {
      const textarea = document.createElement("textarea");
      textarea.value = text;
      textarea.setAttribute("readonly", "");
      textarea.style.position = "fixed";
      textarea.style.opacity = "0";
      document.body.appendChild(textarea);
      textarea.select();
      const ok = document.execCommand("copy");
      document.body.removeChild(textarea);
      ok ? resolve() : reject(new Error("copy failed"));
    });
  }

  function copyToClipboard(text) {
    writeClipboard(text).then(() => {
      setCopiedValue(text);
      const notification = document.getElementById("notification");
      notification.textContent = `${text} ${t.copied}`;
      notification.classList.add("show");

      setTimeout(() => {
        notification.classList.remove("show");
        setCopiedValue((current) => (current === text ? null : current));
      }, 2000);
    });
  }
  return (
    <>
      <header className="about-me-header">
        {bannerImages.map((img, i) => (
          <div
            key={i}
            className={`slide ${i === index ? "active" : ""}`}
            style={{ backgroundImage: `url(${img})` }} // 仅保留图片路径
          />
        ))}
        <div className="header-text">{t.header}</div>

        <div className="arrow-container">
          <div className="arrow"></div>
        </div>
      </header>
      <div className="contentPage">
        <div className="profile-card">
          <div className="profile-content">
            <div className="single-column">
              <div className="section intro">
                <div className="section-title">{t.personalInfo}</div>
                {t.introLines.map((line) => (
                  <p className="intro-line" key={line[0].label}>
                    {line.map((item, itemIndex) => (
                      <React.Fragment key={item.label}>
                        {itemIndex > 0 && <span className="intro-sep">|</span>}
                        <span className="intro-label">{item.label}</span>
                        {item.copy ? (
                          <button
                            type="button"
                            className="intro-copy"
                            title={t.clickToCopy}
                            onClick={() => copyToClipboard(item.value)}
                          >
                            {item.value}
                            <svg
                              className={copiedValue === item.value ? "intro-copy-icon copied" : "intro-copy-icon"}
                              xmlns="http://www.w3.org/2000/svg"
                              width="14"
                              height="14"
                              viewBox="0 0 24 24"
                              fill="none"
                              stroke="currentColor"
                              strokeWidth="2"
                              strokeLinecap="round"
                              strokeLinejoin="round"
                            >
                              {copiedValue === item.value ? (
                                <path d="M20 6 9 17l-5-5" />
                              ) : (
                                <>
                                  <rect width="14" height="14" x="8" y="8" rx="2" ry="2" />
                                  <path d="M4 16c-1.1 0-2-.9-2-2V4c0-1.1.9-2 2-2h10c1.1 0 2 .9 2 2" />
                                </>
                              )}
                            </svg>
                          </button>
                        ) : Array.isArray(item.value) ? (
                          item.value.map((part, partIndex) => (
                            <React.Fragment key={part}>
                              {partIndex > 0 && <span className="intro-sep">|</span>}
                              {part}
                            </React.Fragment>
                          ))
                        ) : (
                          item.value
                        )}
                      </React.Fragment>
                    ))}
                  </p>
                ))}
              </div>

              <div className="section">
                <div className="section-title">{t.education}</div>
                {t.schools.map((school) => (
                  <div className="resume-item" key={school.name}>
                    <div className="resume-row">
                      <span className="resume-name">{school.name}</span>
                      <span className="resume-meta">{school.date}</span>
                    </div>
                    <div className="resume-row">
                      <span>{school.detail}</span>
                      <span className="resume-meta">{school.location}</span>
                    </div>
                  </div>
                ))}
              </div>

              <div className="section">
                <div className="section-title">{t.workExperience}</div>
                {t.jobs.map((job) => (
                  <div className="resume-item" key={job.company}>
                    <div className="resume-row">
                      <span className="resume-name">{job.company}</span>
                      <span className="resume-meta">{job.date}</span>
                    </div>
                    <div className="resume-row">
                      <span>{job.role}</span>
                      <span className="resume-meta">{job.location}</span>
                    </div>
                    <p className="resume-line">
                      {t.summaryLabel}
                      {job.summary}
                    </p>
                    <ul className="resume-bullets">
                      {job.bullets.map((bullet) => (
                        <li key={bullet}>{bullet}</li>
                      ))}
                    </ul>
                    <p className="resume-line">
                      {t.techStackLabel}
                      {job.techStack.join(" · ")}
                    </p>
                  </div>
                ))}
              </div>

              <div className="section">
                <div className="section-title">{t.technicalSkills}</div>
                <div className="skills-container">
                  {t.skills.map((skill, skillIndex) => (
                    <div className="skill-item" key={skill}>
                      <i className={`${skillIcons[skillIndex]} skill-icon`}></i>
                      <span>{skill}</span>
                    </div>
                  ))}
                </div>
              </div>

              <div className="section">
                <div className="section-title">{t.languages}</div>
                <div className="skills-container">
                  {t.languageItems.map((languageItem) => (
                    <div className="skill-item" key={languageItem}>
                      <i className="fas fa-language skill-icon"></i>
                      <span>{languageItem}</span>
                    </div>
                  ))}
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>
      <div id="notification" className="notification"></div>
    </>
  );
}
